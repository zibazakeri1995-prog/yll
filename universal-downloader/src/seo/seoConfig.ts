export function getSeoForPath(path: string): SeoPage | undefined {
  // Remove trailing slash and query params
  const cleanPath = path.split('?')[0].replace(/\/$/, '');
  
  // Find matching SEO config
  for (const [key, config] of Object.entries(seoConfig)) {
    if (config.path === cleanPath) {
      return config;
    }
  }
  
  // Check for dynamic routes like /blog/:slug
  if (cleanPath.startsWith('/blog/')) {
    return {
      path: cleanPath,
      title: 'Blog Post',
      description: 'Read our latest blog post.',
    };
  }
  
  return seoConfig.home;
}
